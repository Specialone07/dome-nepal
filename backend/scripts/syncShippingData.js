// Generates frontend/src/data/nepalShipping.js from the backend rate table so both stay identical.
const fs = require('fs');
const path = require('path');
const { buildPublicTable } = require('../utils/nepalShipping');

const out = path.join(__dirname, '../../frontend/src/data/nepalShipping.js');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, `// AUTO-GENERATED by backend/scripts/syncShippingData.js — do not edit by hand.\nexport const NEPAL_SHIPPING = ${JSON.stringify(buildPublicTable(), null, 2)}\n`);
console.log('Wrote', out);
